export function fillIllusionCopy(template: string): string {
	return template.replace(/\{(\w+)\}/g, (whole, name: string) => {
		return name in ILLUSION_COPY_VARS
			? ILLUSION_COPY_VARS[name as keyof typeof ILLUSION_COPY_VARS]
			: whole;
	});
}
