#!/usr/bin/env node
/**
 * Build WebP orbit variants for the extra studio exports.
 * Sources: data/custom/*.webp (repo root, not shipped)
 * Output:  frontend/static/images/custom/<id>-480.webp
 *          frontend/src/lib/custom-images.ts
 *
 * Identical bytes are dropped, so re-exporting the same generation twice does
 * not put the same picture in the orbit twice. Re-run when data/custom changes.
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __dirname = dirname(fileURLToPath(import.meta.url));
const sourceDir = join(__dirname, '..', '..', 'data', 'custom');
const outDir = join(__dirname, '..', 'static', 'images', 'custom');
const catalogPath = join(__dirname, '..', 'src', 'lib', 'custom-images.ts');

const widths = [480];
const quality = 82;

const KNOWN_MODELS = [
	'sdxl-base',
	'sdxl-fast',
	'sdxl-hypersd',
	'sdxl-turbo',
	'sd-turbo',
	'ssd-1b-lightning',
	'ssd-1b',
	'dreamshaper-lcm',
	'vega-rt'
];

/**
 * Filenames carry the prompt and sometimes the model, in a few shapes:
 *   02-porcelain-teacup-still-life.webp
 *   <run>__01-rain-soaked-neon-alley__sdxl-base__<params>__<size>.webp
 */
function describe(file) {
	const stem = file.replace(/\.webp$/i, '');
	const parts = stem.split('__');
	const promptPart = parts.length > 1 ? parts[1] : parts[0];
	const model = parts.find((part) => KNOWN_MODELS.includes(part)) ?? null;
	const slug = promptPart.replace(/^\d+-/, '');
	const words = slug.replace(/-/g, ' ').trim();
	return { alt: words.charAt(0).toUpperCase() + words.slice(1), model, slug };
}

const files = (await readdir(sourceDir)).filter((file) => /\.webp$/i.test(file)).sort();
await mkdir(outDir, { recursive: true });

const seen = new Map();
const catalog = [];
let duplicates = 0;

for (const file of files) {
	const bytes = await readFile(join(sourceDir, file));
	const digest = createHash('md5').update(bytes).digest('hex');
	if (seen.has(digest)) {
		duplicates += 1;
		continue;
	}
	seen.set(digest, file);

	const id = digest.slice(0, 8);
	const { alt, model, slug } = describe(file);
	const meta = await sharp(bytes).metadata();
	for (const width of widths) {
		await sharp(bytes)
			.resize({ width })
			.webp({ quality })
			.toFile(join(outDir, `${id}-${width}.webp`));
	}
	catalog.push({ id, alt, model, slug, width: meta.width, height: meta.height });
}

const entries = catalog
	.map(
		(row) => `	{
		id: '${row.id}',
		alt: ${JSON.stringify(row.alt)},
		model: ${row.model ? `'${row.model}'` : 'null'},
		width: ${row.width},
		height: ${row.height}
	}`
	)
	.join(',\n');

await writeFile(
	catalogPath,
	`// Generated by scripts/generate-custom-images.mjs from data/custom. Do not edit.
// Extra studio exports for the orbit. The caption is the prompt slug from each
// file name; the model is the one that produced it where the name records it.
export type CustomImage = {
	id: string;
	alt: string;
	model: string | null;
	width: number;
	height: number;
};

export const customImages: CustomImage[] = [
${entries}
];

export function customSources(image: CustomImage) {
	return {
		src: \`/images/custom/\${image.id}-480.webp\`,
		srcset: \`/images/custom/\${image.id}-480.webp 480w\`
	};
}
`,
	'utf8'
);

console.log(`custom images: ${catalog.length} kept, ${duplicates} duplicate(s) skipped`);
