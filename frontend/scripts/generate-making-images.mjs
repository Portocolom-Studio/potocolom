#!/usr/bin/env node
/**
 * Build WebP variants for the "what people are making" wall.
 * Sources: data/making/*.webp (repo root, not shipped)
 * Output:  frontend/static/images/making/<id>-{320,480}.webp
 *          frontend/src/lib/making-images.ts
 *
 * Identical bytes are dropped. Re-run when data/making changes.
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __dirname = dirname(fileURLToPath(import.meta.url));
const sourceDir = join(__dirname, '..', '..', 'data', 'making');
const outDir = join(__dirname, '..', 'static', 'images', 'making');
const catalogPath = join(__dirname, '..', 'src', 'lib', 'making-images.ts');

const widths = [320, 480];
const quality = 82;

const KNOWN_MODELS = [
	'sdxl-base',
	'sdxl-fast',
	'sdxl-hypersd',
	'sdxl-turbo',
	'sd-turbo',
	'ssd-1b-lightning',
	'ssd-1b',
	'dreamshaper-lcm',
	'vega-rt',
	'sd35-medium'
];

/**
 * Filenames carry the prompt and sometimes the model, in a few shapes:
 *   <uuid>.webp
 *   <model>__<prompt-slug>__<id>.webp
 *   <run>__01-rain-soaked-neon-alley__sdxl-base__<params>__<size>.webp
 */
function describe(file) {
	const stem = file.replace(/\.webp$/i, '').replace(/ \(\d+\)$/, '');
	const parts = stem.split('__');
	const model = parts.find((part) => KNOWN_MODELS.includes(part)) ?? null;
	let promptPart = parts.length > 1 ? parts[1] : parts[0];
	if (KNOWN_MODELS.includes(promptPart) && parts[2]) {
		promptPart = parts[2];
	}
	// UUID-only exports have nothing useful in the name.
	if (/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(promptPart)) {
		return { alt: model ? `${model} generation` : 'Studio generation', model, slug: promptPart };
	}
	const slug = promptPart.replace(/^\d+-/, '');
	const words = slug.replace(/-/g, ' ').trim();
	const alt = words ? words.charAt(0).toUpperCase() + words.slice(1) : 'Studio generation';
	return { alt, model, slug };
}

const files = (await readdir(sourceDir)).filter((file) => /\.webp$/i.test(file)).sort();
await mkdir(outDir, { recursive: true });

const seen = new Map();
const catalog = [];
let duplicates = 0;

for (const file of files) {
	const bytes = await readFile(join(sourceDir, file));
	const digest = createHash('md5').update(bytes).digest('hex');
	if (seen.has(digest)) {
		duplicates += 1;
		continue;
	}
	seen.set(digest, file);

	const id = digest.slice(0, 8);
	const { alt, model, slug } = describe(file);
	const meta = await sharp(bytes).metadata();
	for (const width of widths) {
		await sharp(bytes)
			.resize({ width })
			.webp({ quality })
			.toFile(join(outDir, `${id}-${width}.webp`));
	}
	catalog.push({ id, alt, model, slug, width: meta.width, height: meta.height });
}

const entries = catalog
	.map(
		(row) => `	{
		id: '${row.id}',
		alt: ${JSON.stringify(row.alt)},
		model: ${row.model ? `'${row.model}'` : 'null'},
		width: ${row.width},
		height: ${row.height}
	}`
	)
	.join(',\n');

await writeFile(
	catalogPath,
	`// Generated by scripts/generate-making-images.mjs from data/making. Do not edit.
// Gallery wall for the orbit "what people are making" section.
export type MakingImage = {
	id: string;
	alt: string;
	model: string | null;
	width: number;
	height: number;
};

export const makingImages: MakingImage[] = [
${entries}
];

export function makingSources(image: MakingImage) {
	return {
		src: \`/images/making/\${image.id}-480.webp\`,
		srcset: \`/images/making/\${image.id}-320.webp 320w, /images/making/\${image.id}-480.webp 480w\`
	};
}
`,
	'utf8'
);

console.log(`making images: ${catalog.length} kept, ${duplicates} duplicate(s) skipped`);
