#!/usr/bin/env bash
# Rejects AI attribution and decorative characters in a commit message or a
# pull request body. The commit-msg hook and commit-hygiene CI both call it,
# so the two gates apply the same rules.
set -euo pipefail

if [ "$#" -ne 1 ]; then
	echo "usage: check-commit-msg.sh <message-file>" >&2
	exit 2
fi

exec python3 - "$1" <<'PY'
import re
import sys

TOOL = r"(claude|chatgpt|copilot|codex|cursor|gemini|gpt-?\d[\w.-]*)"
PRODUCT = r"(\s+(code|agent|ide|code\s+assist|opus|sonnet|haiku|fable|\d[\w.-]*))*"
# A co-author is judged by an exact AI identity, never by a substring of a
# human name or a company domain: Jean-Claude Dupont and alice@openai.com are
# people, dependabot is not an AI author.
AI_CO_AUTHOR = re.compile(
    r"noreply@anthropic\.com|noreply@openai\.com|cursoragent@cursor\.com"
    r"|\+copilot@users\.noreply\.github\.com|" + TOOL + r"[\w-]*\[bot\]"
    r"|^(github\s+)?" + TOOL + PRODUCT + r"\s*(<|$)",
    re.IGNORECASE,
)
CO_AUTHOR = re.compile(r"^\s*co-authored-by\s*:(.*)", re.IGNORECASE)
MARKDOWN = re.compile(r"[*_`\[\]]")
SPACES = re.compile(r"\s+")
# The tool name must end the credit or open its link, so "generated with
# cursor pagination" and "generated by Claude Martin's script" are prose.
GENERATED = re.compile(
    r"^\W*generated (with|by) (github )?" + TOOL + PRODUCT + r"(?=\s*(\(|[.!]?\s*$))",
    re.IGNORECASE,
)
# Accented letters are not listed, so names such as Jose still pass.
BANNED = [
    (0x2010, 0x2027),
    (0x00A0, 0x00A0),
    (0x00D7, 0x00D7),
    (0x203C, 0x203C),
    (0x2049, 0x2049),
    (0x20E3, 0x20E3),
    (0x2190, 0x21FF),
    (0x2264, 0x2265),
    (0x2300, 0x23FF),
    (0x2500, 0x257F),
    (0x2600, 0x27BF),
    (0x2B00, 0x2BFF),
    (0x3030, 0x3030),
    (0x303D, 0x303D),
    (0x3297, 0x3297),
    (0x3299, 0x3299),
    (0xFE0F, 0xFE0F),
    (0x1F000, 0x1FAFF),
]

path = sys.argv[1]
try:
    with open(path, encoding="utf-8") as handle:
        lines = handle.read().splitlines()
except (OSError, UnicodeDecodeError) as error:
    print(f"check-commit-msg: cannot read {path} as UTF-8: {error}", file=sys.stderr)
    sys.exit(2)

problems = []
for number, line in enumerate(lines, 1):
    # Git folds an indented line into the trailer above it.
    trailer = line
    for following in lines[number:]:
        if not following[:1].isspace():
            break
        trailer += " " + following.strip()
    co_author = CO_AUTHOR.match(trailer)
    if (co_author and AI_CO_AUTHOR.search(co_author.group(1).strip())) or GENERATED.search(SPACES.sub(" ", MARKDOWN.sub("", line))):
        problems.append((number, "AI attribution", line))
    for char in line:
        if any(low <= ord(char) <= high for low, high in BANNED):
            problems.append((number, f"banned character U+{ord(char):04X}", line))
            break

for number, reason, line in problems:
    print(f"check-commit-msg: line {number}: {reason}: {line}", file=sys.stderr)
sys.exit(1 if problems else 0)
PY
