#!/usr/bin/env bash
# Self-test for scripts/check-commit-msg.sh: each case writes a message to a
# temp file and asserts the exit status, so the rules must reject what they
# name and must still pass human names and ordinary prose.
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
check="$root/scripts/check-commit-msg.sh"
dir=$(mktemp -d)
trap 'rm -rf "$dir"' EXIT

failures=0

# expect <pass|fail> <case-name> <message printf %b text>
expect() {
	local want="$1" name="$2" file="$dir/$2.txt" code=0 err
	printf '%b' "$3" >"$file"
	err=$(bash "$check" "$file" 2>&1 >/dev/null) || code=$?
	if [ "$want" = pass ] && [ "$code" -eq 0 ]; then
		echo "PASS: $name"
	elif [ "$want" = fail ] && [ "$code" -eq 1 ] && grep -q '^check-commit-msg: line ' <<<"$err"; then
		echo "PASS: $name (rejected: $err)"
	else
		echo "FAIL: $name (want $want, exit $code): $err"
		failures=$((failures + 1))
	fi
}

expect pass clean 'Fix the ruleset mirror\n\nExplain the change in plain words.\n\nSigned-off-by: Leon Fuller <l.elliottfuller@gmail.com>\n'
expect pass accented-name 'Add the importer\n\nSigned-off-by: Jos\xc3\xa9 Garc\xc3\xada <jose@example.com>\n'
expect pass human-co-author 'Add the importer\n\nCo-Authored-By: Jean-Claude Dupont <jean@example.org>\n'
expect pass prose-generated-with 'Tests generated with cursor pagination.\n'
expect pass revert-subject 'Revert "Tests generated with cursor pagination"\n'
expect pass dependabot-co-author 'Bump x\n\nCo-authored-by: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>\n'
expect pass vendor-employee 'Add it\n\nCo-authored-by: Alice Smith <alice@openai.com>\n'
expect pass name-prefix 'Generated by Claudette Martin.\n'
expect fail gemini-co-author 'Add it\n\nCo-authored-by: Gemini Code Assist <gemini-code-assist@google.com>\n'
expect fail generated-cursor-link 'Generated with [Cursor](https://cursor.com)\n'
expect fail generated-underscore '__Generated with Claude Code__\n'
expect fail generated-split-bold '**Generated** with **Claude Code**\n'
expect fail generated-github-copilot 'Generated with GitHub Copilot\n'
expect fail double-exclamation 'Done \xe2\x80\xbc\n'
expect fail circled-ideograph 'Done \xe3\x8a\x97\n'
expect fail generated-gpt-4o 'Generated with GPT-4o-mini\n'
expect fail cursor-co-author 'Add it\n\nCo-authored-by: Cursor <cursor@cursor.com>\n'
expect fail generated-cursor-period 'Generated with Cursor.\n'
expect fail generated-double-space 'Generated with  Claude Code\n'
expect pass human-claude 'Generated by Claude Martin'"'"'s import script.\n'
expect fail codex-bot-co-author 'Add it\n\nCo-authored-by: chatgpt-codex-connector[bot] <199175422+chatgpt-codex-connector[bot]@users.noreply.github.com>\n'
expect fail generated-model 'Generated with Claude Opus 5.5\n'
expect fail generated-version 'Generated with Claude Code v2.0.1\n'
expect fail generated-colon-link 'Generated with Claude Code: https://claude.com/claude-code\n'
expect fail generated-bare-colon 'Generated with Cursor: https://cursor.com\n'
expect fail generated-cli 'Generated with GitHub Copilot CLI\n'
expect fail gemini-cli-co-author 'Add it\n\nCo-authored-by: Gemini CLI <gemini@google.com>\n'
expect fail generated-html 'Done\n\n<sub>Generated with [Claude Code](https://claude.com/claude-code)</sub>\n'
expect fail generated-checkbox '- [x] Generated with Claude Code\n'
expect fail generated-numbered '1. Generated with Claude Code\n'
expect fail heading-dash '# Description \xe2\x80\x94 why\n'
expect fail heading-generated '# Generated with Claude Code\n'
expect fail spaced-trailer 'Add the importer\n\nCo-Authored-By : Claude <noreply@anthropic.com>\n'
expect fail folded-trailer 'Add the importer\n\nCo-Authored-By:\n Claude <noreply@anthropic.com>\n'
expect fail copilot-co-author 'Add the importer\n\nCo-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>\n'
expect fail generated-bold 'Generated with **Claude Code**\n'
expect fail generated-gpt 'Generated with GPT-5\n'
expect fail watch-emoji 'Ship it \xe2\x8c\x9a\n'
expect fail keycap-emoji 'Step 1\xef\xb8\x8f\xe2\x83\xa3\n'
expect fail claude-co-authored-by 'Add the importer\n\nCo-Authored-By: Claude Haiku 5.5 <noreply@anthropic.com>\n'
expect fail em-dash 'Fix the importer \xe2\x80\x94 quickly\n'
expect fail arrow 'Map a -> b \xe2\x86\x92 c\n'
expect fail emoji 'Ship it \xf0\x9f\xa4\x96\n'
expect fail generated-with 'Add the importer\n\nGenerated with [Claude Code](https://claude.com/claude-code)\n'

# Folding once per trailer keeps a long indented body linear; it took 30 s
# when every line rescanned the lines below it.
python3 -c 'print("Add it\n" + "  indented\n" * 16000)' >"$dir/long.txt"
if timeout 5 bash "$check" "$dir/long.txt"; then
	echo "PASS: long-indented"
else
	echo "FAIL: long-indented (slow or rejected)"
	failures=$((failures + 1))
fi

if [ "$failures" -gt 0 ]; then
	echo "commit message check self-test: ${failures} case(s) failed"
	exit 1
fi
echo "commit message check self-test: all cases passed"
